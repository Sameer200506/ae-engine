/*
 * Offline mock of an OpenAI-compatible API.
 *
 * Why this exists: it lets you run and demo the whole product with zero API
 * keys, and it makes the chat + retrieval loop testable end to end without a
 * network dependency or a token bill.
 *
 *   npm run mock:llm
 *   # then, in .env.local:
 *   #   LLM_BASE_URL=http://localhost:8787/v1
 *   #   LLM_API_KEY=mock
 *
 * It is NOT a language model. Replies are deterministic and derived purely from
 * the request, which is exactly what makes it useful in tests.
 *
 *   POST /v1/chat/completions  -> SSE stream, word by word
 *   POST /v1/embeddings        -> deterministic 64-dim bag-of-words vector
 */

import http from "node:http";

const PORT = Number(process.env.MOCK_LLM_PORT || 8787);
const DIM = 64;
const STREAM_DELAY_MS = Number(process.env.MOCK_STREAM_DELAY_MS || 6);

/**
 * Deterministic hashed bag-of-words embedding.
 *
 * Unrelated text lands at ~0 similarity while text sharing vocabulary lands
 * high, so retrieval ranking is genuinely exercised rather than faked.
 */
function embed(text) {
  const vector = new Array(DIM).fill(0);

  // Unigrams plus bigrams give a little word-order sensitivity.
  const words = String(text).toLowerCase().match(/[a-z0-9]+/g) || [];
  const tokens = [...words];
  for (let i = 0; i < words.length - 1; i++) tokens.push(`${words[i]}_${words[i + 1]}`);

  for (const token of tokens) {
    vector[hash(token) % DIM] += 1;
  }

  let sum = 0;
  for (const value of vector) sum += value * value;
  const norm = Math.sqrt(sum);
  return norm ? vector.map((v) => v / norm) : vector;
}

function hash(token) {
  let h = 2166136261;
  for (let i = 0; i < token.length; i++) {
    h ^= token.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return Math.abs(h);
}

function readBody(req) {
  return new Promise((resolve, reject) => {
    let raw = "";
    req.on("data", (chunk) => (raw += chunk));
    req.on("end", () => {
      try {
        resolve(raw ? JSON.parse(raw) : {});
      } catch (error) {
        reject(error);
      }
    });
    req.on("error", reject);
  });
}

function json(res, status, payload) {
  const body = JSON.stringify(payload);
  res.writeHead(status, {
    "Content-Type": "application/json",
    "Content-Length": Buffer.byteLength(body),
  });
  res.end(body);
}

/** Pull the source titles the app injected from the knowledge base. */
function extractSources(systemPrompt) {
  const titles = [];
  const re = /^\[\d+\] Source: (.+)$/gm;
  let match;
  while ((match = re.exec(systemPrompt)) !== null) titles.push(match[1].trim());
  return titles;
}

function buildReply(messages) {
  const system = messages.find((m) => m.role === "system")?.content ?? "";
  const lastUser = [...messages].reverse().find((m) => m.role === "user")?.content ?? "";
  const titles = extractSources(system);

  if (titles.length) {
    return [
      `Mock reply grounded in ${titles.length} retrieved excerpt(s).`,
      "",
      `The knowledge base supplied: ${titles.map((t, i) => `[${i + 1}] ${t}`).join(", ")}.`,
      "",
      `You asked: "${lastUser}".`,
      "",
      "| Check | Result |",
      "| --- | --- |",
      "| Retrieval | wired |",
      "| Streaming | wired |",
      "",
      "This text is generated by scripts/mock-llm.mjs, not by a language model.",
    ].join("\n");
  }

  return [
    "Mock reply with no retrieved context.",
    "",
    `You asked: "${lastUser}".`,
    "",
    "No knowledge-base excerpts were attached to this request, so there is nothing to cite.",
  ].join("\n");
}

async function handleChat(req, res, body) {
  const reply = buildReply(body.messages ?? []);

  res.writeHead(200, {
    "Content-Type": "text/event-stream; charset=utf-8",
    "Cache-Control": "no-cache, no-transform",
    Connection: "keep-alive",
    "X-Accel-Buffering": "no",
  });

  // Stream as word-ish chunks so the client's incremental rendering is exercised.
  const pieces = reply.match(/\S+\s*/g) ?? [reply];
  for (const piece of pieces) {
    res.write(
      `data: ${JSON.stringify({
        id: "mock",
        object: "chat.completion.chunk",
        model: body.model ?? "mock-model",
        choices: [{ index: 0, delta: { content: piece }, finish_reason: null }],
      })}\n\n`,
    );
    if (STREAM_DELAY_MS) await new Promise((r) => setTimeout(r, STREAM_DELAY_MS));
  }

  res.write(
    `data: ${JSON.stringify({
      id: "mock",
      object: "chat.completion.chunk",
      choices: [{ index: 0, delta: {}, finish_reason: "stop" }],
    })}\n\n`,
  );
  res.write("data: [DONE]\n\n");
  res.end();
}

async function handleEmbeddings(req, res, body) {
  const input = Array.isArray(body.input) ? body.input : [body.input ?? ""];
  json(res, 200, {
    object: "list",
    model: body.model ?? "mock-embedding",
    data: input.map((text, index) => ({ object: "embedding", index, embedding: embed(text) })),
  });
}

const server = http.createServer(async (req, res) => {
  const url = new URL(req.url, `http://localhost:${PORT}`);

  try {
    if (req.method === "POST" && url.pathname.endsWith("/chat/completions")) {
      return await handleChat(req, res, await readBody(req));
    }
    if (req.method === "POST" && url.pathname.endsWith("/embeddings")) {
      return await handleEmbeddings(req, res, await readBody(req));
    }
    if (url.pathname === "/health") {
      return json(res, 200, { ok: true, dims: DIM });
    }
    return json(res, 404, { error: { message: `No mock route for ${req.method} ${url.pathname}` } });
  } catch (error) {
    return json(res, 500, { error: { message: String(error) } });
  }
});

server.listen(PORT, () => {
  console.log(`mock LLM listening on http://localhost:${PORT}/v1`);
  console.log(`  embeddings: ${DIM} dims, deterministic bag-of-words`);
  console.log(`  chat: SSE, ${STREAM_DELAY_MS}ms per chunk`);
});
